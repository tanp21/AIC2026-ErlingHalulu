"""Exact PTS-based thumbnail extraction via ffmpeg + disk cache."""
import hashlib
import os
import subprocess
import threading
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CACHE_DIR = Path(os.environ.get("AIC_THUMB_CACHE_DIR", ROOT / ".thumb_cache"))
#: The organisers' own keyframe images, resized offline by
#: ``scripts.indexing.build_keyframe_thumbnails``, keyed by the (video_id, frame_idx) a search
#: hit reports. Only the N traffic-camera groups have one: their embeddings were taken from
#: those JPEGs, and their videos carry no usable frame timestamps, so ffmpeg can extract
#: nothing from them at all -- see `stored_keyframe`.
KEYFRAME_DIR = Path(os.environ.get(
    "AIC_KEYFRAME_THUMB_DIR",
    Path(os.environ.get("AIC_DATA_DIR", ROOT / "data")) / "2026" / "keyframe_thumbs"))
#: Every width the store is built at, largest first -- what `stored_keyframe_largest` walks for
#: `/frame`. `/thumb` asks for its own width directly (the closed set the route validates).
KEYFRAME_WIDTHS = (1280, 640, 320, 160)
#: Room for one index-based extraction (see `ordinal_command`): a full decode of the video.
ORDINAL_TIMEOUT = int(os.environ.get("AIC_THUMB_ORDINAL_TIMEOUT", "180"))
# Sized to comfortably hold every indexed keyframe pre-generated by
# scripts.media.pregenerate_thumbnails (~850k keyframes x a few KB each, well
# under 10GB) plus normal on-demand browsing, without evicting the pre-warmed set.
MAX_CACHE_BYTES = int(os.environ.get("AIC_THUMB_CACHE_MAX_BYTES", 20 * 1024**3))
# Measured on the 6-core/12-thread production host, each ffmpeg call pinned to
# -threads 1 (see ffmpeg_command below -- without that pin, ffmpeg auto-threads
# per process and N concurrent calls oversubscribe the CPU by a further factor of
# N, which is what capped this at ~8 and made throughput degrade over a long
# run): throughput scales close to linearly up to ~12 concurrent (one per logical
# core) and plateaus around 35/s beyond that. 12 balances bulk throughput against
# leaving headroom for FAISS/Elasticsearch during a search-heavy moment.
_ffmpeg_slots = threading.BoundedSemaphore(int(os.environ.get("AIC_THUMB_FFMPEG_SLOTS", "12")))
_key_locks = tuple(threading.Lock() for _ in range(256))
_cache_guard = threading.Lock()
_known_cache_bytes = None


def _key_lock(key):
    return _key_locks[int(key[:8], 16) % len(_key_locks)]


def _prune_cache(current):
    global _known_cache_bytes
    with _cache_guard:
        if _known_cache_bytes is None:
            # Only pay for a full directory listing once, to seed the running total.
            _known_cache_bytes = sum(
                path.stat().st_size for path in CACHE_DIR.glob("*.jpg") if path.exists()
            )
        else:
            _known_cache_bytes += current.stat().st_size
        if _known_cache_bytes <= MAX_CACHE_BYTES:
            return
        # Listing the directory is only needed for the eviction pass below, so it's
        # deferred until we're actually over budget -- doing it on every write made
        # each write O(n) in the cache's current file count (an unconditional
        # `CACHE_DIR.glob()` before this check), which is O(n^2) over a long run and
        # was the real cause of the 850k-thumbnail pregeneration job degrading from
        # ~18/s to ~7/s over its first hour, not CPU contention.
        files = list(CACHE_DIR.glob("*.jpg"))
        for path in sorted(files, key=lambda item: item.stat().st_mtime):
            if path == current or not path.exists():
                continue
            size = path.stat().st_size
            path.unlink(missing_ok=True)
            _known_cache_bytes -= size
            if _known_cache_bytes <= MAX_CACHE_BYTES:
                break


def carries_no_frame_timestamps(video_path):
    """True for the N (traffic-camera) groups, whose containers cannot be sought or matched.

    BTC encodes them VFR, and the files they ship carry a sample table that disagrees with
    their packets: `ffprobe` reports a best-effort timeline (which is what the frame maps were
    built from, and what our index times mean), but no frame in the stream actually carries
    those timestamps. `select=eq(pts,...)` therefore matches nothing, and `-ss` into one of
    these files decodes no frame at all -- `/thumb` answered 500 for every N frame. The frame's
    *position* is the one identity that survives, so those videos are extracted by index.
    """
    return Path(video_path).stem.split("_", 1)[0].startswith("N")


def ordinal_command(video_path, frame_idx, output, w=320):
    """Extract by decoded position: no seek (there is no usable one) and `eq(n,...)`.

    Costs a decode from the start of the file -- seconds per frame rather than milliseconds --
    which is why the keyframes the UI actually shows come from the stored keyframe images
    (`stored_keyframe`) and this is the path for everything else (a neighbour frame the agent
    walks to, a frame with no stored image).
    """
    filters = [f"select=eq(n\\,{int(frame_idx)})"]
    if w > 0:
        filters.append(f"scale={w}:-2")
    return [
        "ffmpeg", "-y", "-loglevel", "error", "-threads", "1", "-filter_threads", "1",
        "-i", str(video_path), "-an", "-vf", ",".join(filters),
        "-frames:v", "1", "-vsync", "0", "-q:v", "4", str(output),
    ]


def ffmpeg_command(video_path, frame_idx, mapping, output, w=320):
    if carries_no_frame_timestamps(video_path):
        return ordinal_command(video_path, frame_idx, output, w)
    pts = int(mapping.pts[frame_idx])
    timestamp = mapping.source_time(frame_idx)
    filters = [f"select=eq(pts\\,{pts})"]
    if w > 0:
        filters.append(f"scale={w}:-2")
    return [
        # -threads 1: extracting one frame from a small seek window gets no benefit from
        # ffmpeg's default auto-threading, which otherwise grabs all visible cores per
        # process -- under N concurrent extractions that oversubscribes the CPU by a
        # factor of N (measured: load average >27 on a 12-thread host with only 8
        # concurrent ffmpeg calls), and throughput degrades over a long bulk run instead
        # of holding steady.
        # -filter_threads 1: -threads only pins the decoder; the scale filter still sizes
        # its slice pool from the visible core count, so each concurrent extraction held
        # ~12 extra threads. Against the container's pids.max=256 that exhausts the
        # thread budget and pthread_create fails with EAGAIN, ffmpeg exits non-zero
        # ("Resource temporarily unavailable"), and /thumb 500s for a large fraction of a
        # cold results page.
        "ffmpeg", "-y", "-loglevel", "error", "-threads", "1", "-filter_threads", "1",
        "-copyts", "-ss", f"{timestamp:.15f}",
        "-i", str(video_path), "-an", "-vf", ",".join(filters),
        "-frames:v", "1", "-vsync", "0", "-q:v", "4", str(output),
    ]


def stored_keyframe(video_id, frame_idx, w=320):
    """The organisers' keyframe image for a frame, or ``None`` to cut one out of the video.

    The N (traffic-camera) groups need this: their videos are VFR with a container that carries
    no usable frame timestamps, so a seek into one decodes nothing and a ``pts`` match finds
    nothing -- `/thumb` answered 500 for every N frame. The images come from the organisers'
    own keyframe archives, which are also what the N embeddings were taken from, so this is
    both the only workable source and the truthful one. Built offline (never resized at
    request time) because `/thumb`'s widths are a closed set: 160, 320, 640.
    """
    if not KEYFRAME_DIR.is_dir():
        return None
    group = video_id.split("_", 1)[0]
    try:
        return (KEYFRAME_DIR / str(w) / group / video_id / f"{frame_idx}.jpg").read_bytes()
    except OSError:
        return None


def stored_keyframe_largest(video_id, frame_idx):
    """The largest stored width for a frame -- what `/frame` serves.

    A host can hold a subset of the widths (the 1280 set is 15 GB; the compute host serves it
    to the agent, which resizes anyway), so this takes the best one present rather than
    falling through to a video ffmpeg cannot read.
    """
    for width in KEYFRAME_WIDTHS:
        data = stored_keyframe(video_id, frame_idx, width)
        if data is not None:
            return data
    return None


def extract(video_path, frame_idx, mapping, w=320):
    CACHE_DIR.mkdir(parents=True, exist_ok=True)
    pts = int(mapping.pts[frame_idx])
    # Keyed by file name, not the full path: the data disk is mounted at a different
    # prefix per environment (host `.../AIC_HCMC/data`, container `/data`), and hashing
    # the absolute path made `scripts.media.pregenerate_thumbnails` (host) write entries
    # the container could never hit -- every live /thumb was a cold ffmpeg run.
    key = hashlib.sha1(
        f"pts-v3:{Path(video_path).name}:{pts}:{mapping.time_base_num}/{mapping.time_base_den}:{w}".encode()
    ).hexdigest()
    out = CACHE_DIR / f"{key}.jpg"
    with _key_lock(key):
        created = False
        if not out.exists():
            temporary = CACHE_DIR / f"{key}.tmp.jpg"
            try:
                with _ffmpeg_slots:
                    subprocess.run(
                        ffmpeg_command(video_path, frame_idx, mapping, temporary, w),
                        check=True,
                        # The index-based path (N) decodes from the start of the file, so it
                        # needs room for a late frame in a ten-minute video; the PTS path seeks
                        # and is done in milliseconds either way.
                        timeout=ORDINAL_TIMEOUT if carries_no_frame_timestamps(video_path) else 30,
                    )
                temporary.replace(out)
                created = True
            finally:
                temporary.unlink(missing_ok=True)
        data = out.read_bytes()
        if created:
            _prune_cache(out)
        return data
