"""Write the HAProxy password file the LAN ingress reads.

    uv run python -m scripts.media.make_lan_users              # prompts, writes haproxy-users.cfg
    uv run python -m scripts.media.make_lan_users --print      # show it, write nothing

`haproxy.lan.cfg` authenticates every teammate with HTTP Basic Auth and stamps the
authenticated username into `X-AIC-User`, which is the whole of the backend's identity
model. That username has to be one of the five in `AIC_ALLOWED_USERS`, so the usernames
here are not chosen -- they are read out of `.env.secure`, and only the passwords are
asked for.

The file it writes is gitignored: it is the team's credentials. It is also the *only*
thing standing between the venue LAN and the corpus, so this refuses a password shorter
than 8 characters rather than letting a throwaway one through.

Hashing uses the standard library's `crypt` (SHA-256, `$5$`), which HAProxy verifies
directly. Python 3.13 removed that module; on such an interpreter this falls back to
HAProxy's `insecure-password`, which stores the password in the clear. That is still
correct -- HAProxy reads both -- and the file never leaves the laptop, but the script
says so loudly rather than doing it quietly.
"""
from __future__ import annotations

import argparse
import getpass
import os
import re
import stat
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DEFAULT_ENV = ROOT / ".env.secure"
DEFAULT_OUTPUT = ROOT / "haproxy-users.cfg"
MIN_PASSWORD = 8

try:  # removed in Python 3.13
    import crypt
except ImportError:  # pragma: no cover - depends on the interpreter, not the code
    crypt = None


def read_env(path: Path) -> dict[str, str]:
    """Parse the KEY=VALUE subset of dotenv syntax that `.env.secure` actually uses."""
    values: dict[str, str] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        values[key.strip()] = value
    return values


def hashing_available() -> bool:
    """Whether this interpreter can produce a hash HAProxy will verify.

    Two ways it cannot: Python 3.13 removed `crypt`, and a Python whose libc has no
    SHA-256 crypt raises `OSError` from `crypt.crypt` -- which is not hypothetical, it is
    what a Nix-built interpreter here does. Probing once, with a real call, is the only
    way to tell; `crypt` imports happily in both cases.
    """
    if crypt is None:
        return False
    try:
        crypt.crypt("probe", crypt.mksalt(crypt.METHOD_SHA256))
    except (OSError, ValueError):
        return False
    return True


def hash_password(password: str) -> tuple[str, str]:
    """`(directive, value)` for one HAProxy userlist entry."""
    if not hashing_available():
        return "insecure-password", password
    return "password", crypt.crypt(password, crypt.mksalt(crypt.METHOD_SHA256))


def build_userlist(users: list[str], passwords: dict[str, str], admin: str) -> str:
    lines = [
        "# Generated by `python -m scripts.media.make_lan_users`. Not in git.",
        "# Read by haproxy.lan.cfg; each username matches one entry in AIC_ALLOWED_USERS.",
        "userlist aic_users",
    ]
    for user in users:
        directive, value = hash_password(passwords[user])
        suffix = "  # admin -- exempt from the /video/ bandwidth limit" if user == admin else ""
        lines.append(f"  user {user} {directive} {value}{suffix}")
    return "\n".join(lines) + "\n"


def prompt_for_passwords(users: list[str]) -> dict[str, str]:
    passwords: dict[str, str] = {}
    for user in users:
        while True:
            first = getpass.getpass(f"password for {user}: ")
            if len(first) < MIN_PASSWORD:
                print(f"  too short -- use at least {MIN_PASSWORD} characters", file=sys.stderr)
                continue
            if first != getpass.getpass(f"repeat it for {user}: "):
                print("  the two entries differ", file=sys.stderr)
                continue
            passwords[user] = first
            break
    return passwords


def _check_username(user: str) -> None:
    # A space or a `#` would split or comment out the line HAProxy parses; `$` starts the
    # crypt hash field.
    if re.search(r"[\s#$]", user):
        raise SystemExit(f"username {user!r} cannot be written to a HAProxy userlist")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--env", type=Path, default=DEFAULT_ENV, help="where the five logins live")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--print", dest="dry_run", action="store_true", help="write nothing")
    args = parser.parse_args()

    if not args.env.exists():
        raise SystemExit(f"{args.env} not found -- it holds AIC_ALLOWED_USERS and AIC_ADMIN_USER")
    env = read_env(args.env)
    users = [part.strip() for part in env.get("AIC_ALLOWED_USERS", "").split(",") if part.strip()]
    admin = env.get("AIC_ADMIN_USER", "").strip()
    if len(users) != 5:
        raise SystemExit(f"expected five logins in AIC_ALLOWED_USERS, found {len(users)}")
    if admin not in users:
        raise SystemExit("AIC_ADMIN_USER is not one of AIC_ALLOWED_USERS")
    for user in users:
        _check_username(user)

    if not hashing_available():
        print(
            "warning: this interpreter cannot produce a crypt hash, so the passwords are\n"
            "         written in the clear (HAProxy's `insecure-password`). The file is\n"
            "         gitignored and stays on this laptop. Running this under the repo's own\n"
            "         venv (uv run) uses an interpreter that can hash them instead.",
            file=sys.stderr,
        )

    text = build_userlist(users, prompt_for_passwords(users), admin)
    if args.dry_run:
        print(text)
        return

    args.output.write_text(text, encoding="utf-8")
    try:
        os.chmod(args.output, stat.S_IRUSR | stat.S_IWUSR)
    except OSError:  # Windows ignores POSIX modes; the ACL there is the user's own by default
        pass
    print(f"wrote {args.output} for {len(users)} users")


if __name__ == "__main__":
    main()
